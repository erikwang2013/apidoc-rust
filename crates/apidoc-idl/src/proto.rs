//! `.proto` → apidoc annotation code, backed by `protox` (pure Rust).
//!
//! Input is parsed from an in-memory resolver: the root file is the only local
//! source available, plus protox's built-in `google/protobuf/*` well-known
//! types. Every other import fails — nothing is read from disk or fetched.

use crate::{ensure_input_size, push_fn, render_param, FnNames, Param, MAX_DEPTH};
use prost_types::{
    field_descriptor_proto::{Label, Type},
    DescriptorProto, FieldDescriptorProto, FileDescriptorProto,
};
use protox::file::{ChainFileResolver, File, FileResolver, GoogleFileResolver};
use protox::{Compiler, Error};
use std::collections::HashMap;
use std::path::Path;

const ROOT: &str = "input.proto";
const TARGET: &str = "http://127.0.0.1:50051";

pub fn generate(source: &str, package: Option<&str>) -> Result<String, String> {
    ensure_input_size(source)?;
    check_imports(source)?;
    let file = parse(source)?;
    Ok(render(&file, package))
}

/// Only the built-in well-known types may be imported; `import "http://…"`
/// and local imports are rejected with a clear line-numbered error.
fn check_imports(source: &str) -> Result<(), String> {
    for (idx, line) in source.lines().enumerate() {
        let line = line.trim();
        let rest = line
            .strip_prefix("import public ")
            .or_else(|| line.strip_prefix("import weak "))
            .or_else(|| line.strip_prefix("import "));
        let Some(rest) = rest else { continue };
        let path = rest.trim_end_matches(';').trim().trim_matches('"');
        if !path.starts_with("google/protobuf/") {
            return Err(format!(
                "line {}: import `{path}` is not supported; only the built-in google/protobuf/* files are available (nothing is read from disk or the network)",
                idx + 1
            ));
        }
    }
    Ok(())
}

fn parse(source: &str) -> Result<FileDescriptorProto, String> {
    struct InMemorySource {
        source: String,
    }

    impl FileResolver for InMemorySource {
        fn resolve_path(&self, path: &Path) -> Option<String> {
            let name = path.file_name().and_then(|n| n.to_str())?;
            (name == ROOT).then(|| ROOT.to_string())
        }

        fn open_file(&self, name: &str) -> Result<File, Error> {
            if name == ROOT {
                File::from_source(name, &self.source)
            } else {
                Err(Error::file_not_found(name))
            }
        }
    }

    let mut resolver = ChainFileResolver::new();
    resolver.add(InMemorySource { source: source.to_string() });
    resolver.add(GoogleFileResolver::new());
    let mut compiler = Compiler::with_file_resolver(resolver);
    compiler.open_file(ROOT).map_err(|e| format!("proto parse error: {e}"))?;
    let mut set = compiler.file_descriptor_set();
    set.file.pop().ok_or_else(|| "proto compiler returned no file".to_string())
}

fn render(file: &FileDescriptorProto, package: Option<&str>) -> String {
    let original_pkg = file.package.clone().unwrap_or_default();
    // `--package` only changes the documented service name; type names in the
    // descriptor still use the original package, so resolution must too.
    let service_pkg = package.map(str::to_string).unwrap_or_else(|| original_pkg.clone());
    let mut messages = HashMap::new();
    collect_messages(&original_pkg, &file.message_type, &mut messages);

    let mut out = String::from("// Generated by apidoc-idl. Do not edit.\n\n");
    let mut names = FnNames::new();
    for service in &file.service {
        let full_service = if service_pkg.is_empty() {
            service.name().to_string()
        } else {
            format!("{service_pkg}.{}", service.name())
        };
        for method in &service.method {
            let fn_name = names.alloc(method.name());
            let (params, mut comments) = message_fields(method.input_type(), &messages);
            let (returned, out_comments) = message_fields(method.output_type(), &messages);
            comments.extend(out_comments);

            out.push_str("#[allow(dead_code)]\n");
            out.push_str(&format!("#[apidoc::title(\"{}\")]\n", method.name()));
            out.push_str(&format!(
                "#[apidoc::protocol(\"grpc\", target = \"{TARGET}\", service = \"{full_service}\", method = \"{}\")]\n",
                method.name()
            ));
            for p in &params {
                out.push_str(&render_param("param", p, true));
                out.push('\n');
            }
            for p in &returned {
                out.push_str(&render_param("returned", p, false));
                out.push('\n');
            }
            push_fn(&mut out, &fn_name, &comments);
        }
    }
    out
}

fn collect_messages<'a>(
    prefix: &str,
    messages: &'a [DescriptorProto],
    out: &mut HashMap<String, &'a DescriptorProto>,
) {
    for msg in messages {
        let full = if prefix.is_empty() {
            msg.name().to_string()
        } else {
            format!("{prefix}.{}", msg.name())
        };
        out.insert(full.clone(), msg);
        collect_messages(&full, &msg.nested_type, out);
    }
}

fn message_fields(
    type_name: &str,
    messages: &HashMap<String, &DescriptorProto>,
) -> (Vec<Param>, Vec<String>) {
    let name = type_name.trim_start_matches('.');
    let Some(msg) = messages.get(name) else {
        // External message (e.g. google.protobuf.Empty): no field model.
        return (Vec::new(), Vec::new());
    };
    let mut stack = vec![name.to_string()];
    fields_of(msg, messages, 0, &mut stack)
}

fn fields_of(
    msg: &DescriptorProto,
    messages: &HashMap<String, &DescriptorProto>,
    depth: usize,
    stack: &mut Vec<String>,
) -> (Vec<Param>, Vec<String>) {
    let mut params = Vec::new();
    let mut comments = Vec::new();
    for field in &msg.field {
        let name = field.name();
        if field.oneof_index.is_some() {
            comments.push(format!("TODO: oneof unsupported: field `{name}`"));
            continue;
        }
        if field.r#type() == Type::Message
            && messages.get(type_name_of(field)).is_some_and(is_map_entry)
        {
            comments.push(format!("TODO: map unsupported: field `{name}`"));
            continue;
        }
        let repeated = field.label() == Label::Repeated;
        let (ty, children, mut field_comments) = field_type(field, messages, depth, stack);
        comments.append(&mut field_comments);
        params.push(Param {
            name: name.to_string(),
            ty: if repeated { "array".to_string() } else { ty },
            field: Some(field.number().to_string()),
            required: !repeated,
            children,
        });
    }
    (params, comments)
}

fn field_type(
    field: &FieldDescriptorProto,
    messages: &HashMap<String, &DescriptorProto>,
    depth: usize,
    stack: &mut Vec<String>,
) -> (String, Vec<Param>, Vec<String>) {
    match field.r#type() {
        Type::Message => {
            let name = type_name_of(field);
            let Some(msg) = messages.get(name) else {
                return ("object".to_string(), Vec::new(), Vec::new());
            };
            if depth >= MAX_DEPTH {
                return (
                    "object".to_string(),
                    Vec::new(),
                    vec!["TODO: message nesting depth limit reached".to_string()],
                );
            }
            if stack.iter().any(|s| s == name) {
                return ("object".to_string(), Vec::new(), Vec::new());
            }
            stack.push(name.to_string());
            let (children, comments) = fields_of(msg, messages, depth + 1, stack);
            stack.pop();
            ("object".to_string(), children, comments)
        }
        Type::Enum => ("enum".to_string(), Vec::new(), Vec::new()),
        Type::Bytes => ("bytes".to_string(), Vec::new(), Vec::new()),
        Type::Bool => ("bool".to_string(), Vec::new(), Vec::new()),
        Type::String => ("string".to_string(), Vec::new(), Vec::new()),
        Type::Double | Type::Float => ("float".to_string(), Vec::new(), Vec::new()),
        Type::Group => ("object".to_string(), Vec::new(), Vec::new()),
        _ => ("int".to_string(), Vec::new(), Vec::new()),
    }
}

fn type_name_of(field: &FieldDescriptorProto) -> &str {
    field.type_name().trim_start_matches('.')
}

fn is_map_entry(msg: &&DescriptorProto) -> bool {
    msg.options.as_ref().and_then(|o| o.map_entry).unwrap_or(false)
}
